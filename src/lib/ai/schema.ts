import { z } from "zod";
import type { FinalDecision, ScreeningStatus, Track } from "../constants";
import type { FlagKind, MissingItem } from "../types";

/**
 * What the model is allowed to return. Deliberately assessment-only: the team's claims and the
 * repository facts are filled in by code, so the model cannot rewrite either.
 * Keep this schema free of length/size keywords: structured outputs support a limited JSON Schema subset,
 * and limits are enforced after parsing in summary.ts.
 */
const refs = z.array(z.string());
const basis = z.enum(["team_claim", "readme", "file_paths"]);

export const modelOutputSchema = z.object({
  overview: z.string(),
  problemSummary: z.string(),
  solutionSummary: z.string(),
  mainFeatures: z.array(z.object({ feature: z.string(), basis, evidenceRefs: refs })),
  technologies: z.array(z.object({ name: z.string(), basis })),
  implementationEvidence: z.array(
    z.object({
      claim: z.string(),
      status: z.enum(["supported", "partially_supported", "not_verified", "contradicted"]),
      evidenceRefs: refs,
      note: z.string(),
    }),
  ),
  alignment: z.object({
    rating: z.enum(["strong", "partial", "weak", "cannot_determine"]),
    reasoning: z.string(),
    evidenceRefs: refs,
  }),
  strengths: z.array(z.object({ statement: z.string(), evidenceRefs: refs })),
  missingInformation: z.array(z.string()),
  judgeQuestions: z.array(z.string()),
  limitations: z.array(z.string()),
});

export type ModelOutput = z.infer<typeof modelOutputSchema>;
export type ImplementationStatus = ModelOutput["implementationEvidence"][number]["status"];

/** JSON Schema sent to the API as the output format. */
export const modelOutputJsonSchema: Record<string, unknown> = (() => {
  const s = z.toJSONSchema(modelOutputSchema) as Record<string, unknown>;
  delete s.$schema;
  return s;
})();

/** Actions Charlie really performed. Anything not listed here must never be claimed. */
export interface ChecksPerformed {
  repositoryMetadata: boolean;
  commitHistory: boolean;
  fileListing: boolean;
  readmeExcerptRead: boolean;
  /** Never performed: submitted source files are not read, only their paths. */
  sourceFilesRead: false;
  codeExecuted: false;
  deploymentTested: false;
  modelEvaluated: false;
}

/** Everything under `claims` is copied verbatim from the submission. It is the team's own statement. */
export interface TeamClaims {
  track: Track;
  challenge: string;
  problem: string;
  solution: string;
  technologies: string[];
  aiToolsDeclared: string;
  externalResourcesDeclared: string;
  testingInstructions: string;
  githubUrl: string;
  demoUrl?: string;
}

/** Deterministic screening output. Copied from the screening result, never generated by the model. */
export interface VerificationSection {
  screeningSource: "live" | "mock";
  status: ScreeningStatus;
  statusExplanation: string;
  finalDecision: FinalDecision;
  missing: MissingItem[];
  flags: { code: string; kind: FlagKind; title: string; detail: string; evidenceUrl?: string; resolved: boolean }[];
  repository?: {
    accessible?: boolean;
    createdAt?: string;
    defaultBranch?: string;
    isFork?: boolean;
    hasReadme?: boolean;
    branchesInspected: string[];
    limitations: string[];
  };
}

export interface ProjectSummary {
  generatedAt: string;
  model: string;
  evidenceFingerprint: string;
  /** Section 1: what the team says. Unverified. */
  claims: TeamClaims;
  /** Section 2: what the deterministic checks found. */
  verification: VerificationSection;
  checksPerformed: ChecksPerformed;
  /** Section 3: what the AI concluded from the evidence above. An assessment, not a fact. */
  assessment: ModelOutput;
  /** What validation changed in the model output. */
  sanitization: { removedOrDowngraded: number; notes: string[] };
}

export type SummaryErrorCode =
  | "not_configured"
  | "timeout"
  | "rate_limited"
  | "api_error"
  | "refusal"
  | "truncated"
  | "malformed";

export interface SummaryError {
  code: SummaryErrorCode;
  message: string;
}

export type SummaryOutcome = { ok: true; summary: ProjectSummary; cached: boolean } | { ok: false; error: SummaryError };
